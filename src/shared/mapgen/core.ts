import { Matrix4, Quaternion, Vector3 } from 'three';
import type { BlockMaterial, PieceKind } from '../blocks';

export type V3 = [number, number, number];
export type Q4 = [number, number, number, number];
export type XZ = [number, number];
export type MatKind =
  | 'concrete' | 'asphalt' | 'paving' | 'grass' | 'water' | 'dirt' | 'rock' | 'metal'
  | 'car' | 'glass' | 'paint' | 'plaster' | 'stone' | 'test' | 'glow'
  /** see-through glazing of the enterable buildings */
  | 'window'
  /** planks: crates, jetties, fences */
  | 'wood'
  /** clay roof tiles */
  | 'tile';

export interface BoxDef { pos: V3; quat: Q4; half: V3; color: number; mat: MatKind; collide: boolean; /** collider only (a model is drawn there) */ hidden?: boolean }
/** glTF props from public/models/arena (Kenney Mini Arena, CC0). */
export type PropModel = 'banner' | 'column' | 'weapon-rack' | 'trophy' | 'block';
/** pos = where the model's base stands; `team` recolours its team-coloured parts. */
export interface PropDef { model: PropModel; pos: V3; quat: Q4; scale: number; team?: number }
/** Painted plane (spawn circle, team name, shop sign). Local plane = XY facing +Z; `quat` orients it. */
export interface DecalDef { kind: 'spawn' | 'text'; pos: V3; quat: Q4; size: [number, number]; color: number; text?: string }
export interface HullDef { points: number[]; color: number; mat: MatKind; collide: boolean }
/** Solid facade block with fake rooms (not generated by the cube map: every building there can be entered). */
export interface BuildingDef { pos: V3; quat: Q4; half: V3; color: number; style: 'tower' | 'office' }
/** Old-town house as one solid block with a gable roof (not generated by the cube map). */
export interface HouseDef { pos: V3; quat: Q4; size: V3; roofH: number; wall: number; roof: number }
export interface TreeDef { pos: V3; up: V3; scale: number; kind: 'tree' | 'bush' }
export interface SpawnDef { pos: V3; quat: Q4; yaw: number }
/** The team's "bed": a crystal on a pedestal. `bed` = crystal centre, `pos` = small floating marker above it. */
export interface StatueDef { team: string; pos: V3; bed: V3; up: V3; color: number; fort: { pos: V3; material: BlockMaterial }[] }
/**
 * A shop counter with its keeper: one in every base hall (team = owner) and neutral ones on the neutral faces
 * (team = ''). keeper: capsule centre, body frame; faces the frame's +Z.
 */
export interface BaseDef { team: string; up: V3; shop: V3; keeper: { pos: V3; quat: Q4 } }
/** Crystal generator on a neutral face's square. */
export interface CrystalSpotDef { pos: V3; up: V3 }
/** Pond (fishing). pos = water surface centre; half = extents in the face frame. team '' = a neutral face. */
export interface PondDef { team: string; pos: V3; up: V3; quat: Q4; half: [number, number] }
/** A gravity plate (see gravity.ts): walk face centre, normal, in-plane axes and half extents, pull range. */
export interface PlateDef { center: V3; up: V3; u: V3; v: V3; hu: number; hv: number; minH: number; range: number }
/** Loose crates and barrels (static for now; kickable later). pos = centre, half = box half size (barrel: radius, h/2, radius). */
export interface CrateDef { pos: V3; quat: Q4; half: V3; kind: 'crate' | 'barrel'; color: number }

/** The six inner faces of the cube: `ny` is the floor (ground at y = -S, up +Y), `px` the wall at x = +S, ... */
export type FaceId = 'ny' | 'py' | 'nx' | 'px' | 'nz' | 'pz';
/** A face: origin = centre of its ground, up = towards the cube centre, quat = its frame (frameForUp(up)). */
export interface FaceDef { id: FaceId; team: string | null; origin: V3; up: V3; quat: Q4; half: number }

/**
 * Navigation of a face, face-local XZ (frame of its up, origin = ground centre): the road graph (corners of the
 * city tiles, edges along the roads), and for a team face its hall (doors, crystal stands).
 */
export interface FaceNav {
  nodes: XZ[];
  edges: [number, number][];
  /** Busy spot NPCs keep away from (the hall / the square). */
  hub: XZ;
  /** Team face only: the hall (centre + half size) and its doors (point outside, point inside). */
  hall?: { c: XZ; half: number };
  doors?: { out: XZ; in: XZ }[];
  bedStands?: XZ[];
  patrol?: XZ[];
}

/** One bridge piece of a lane (the grid slot a player would build it in: same key). */
export interface LanePiece { kind: PieceKind; center: V3; half: V3; quat: Q4; key: string; level: number }

/**
 * The planned bridge over a cube edge, built in the gravity of face `a`: 8 floors from a's rim over the gap to the
 * corner, 16 ramps up along b's wall, a landing level with b's rim (25 pieces). Nothing of it exists at the start:
 * players build it (or their own way), bots lay the missing pieces as they walk it.
 * Paths are face-local XZ: `pathA` on a (rim → corner → landing → a point inside b: walking there turns you onto b),
 * `pathB` on b (b's rim in front of the landing → a point inside the landing: walking there turns you onto a),
 * `back` on a (landing → corner → a's rim).
 */
export interface LaneDef {
  id: string;
  a: FaceId;
  b: FaceId;
  pieces: LanePiece[];
  pathA: XZ[];
  pathB: XZ[];
  back: XZ[];
  /** Road graph nodes where the lane meets each face's streets. */
  nodeA: number;
  nodeB: number;
}

export interface MapData {
  seed: number;
  /** Teams that play (a team with no players gets no face). */
  teams: string[];
  boxes: BoxDef[];
  hulls: HullDef[];
  buildings: BuildingDef[];
  houses: HouseDef[];
  trees: TreeDef[];
  crates: CrateDef[];
  spawns: Record<string, SpawnDef>;
  statues: StatueDef[];
  bases: BaseDef[];
  props: PropDef[];
  decals: DecalDef[];
  crystalSpots: CrystalSpotDef[];
  ponds: PondDef[];
  faces: FaceDef[];
  plates: PlateDef[];
  nav: Record<string, FaceNav>;
  lanes: LaneDef[];
  /** Cube half size (face ground distance from the centre) and the half size of a face's city. */
  cube: { half: number; face: number };
  /** Further than this outside the cube = the void. */
  voidMargin: number;
  killRadius: number;
}

const _v = new Vector3();
const _q = new Quaternion();
const Y = new Vector3(0, 1, 0);

/** Local coordinate frame used to build pieces (face, building, car…) and emit world-space data. */
export class Frame {
  readonly m = new Matrix4();
  constructor(readonly origin: Vector3, readonly q: Quaternion, readonly s = 1) {
    this.m.compose(origin, q, new Vector3(1, 1, 1));
  }
  p(x: number, y: number, z: number): V3 {
    return this.raw(x * this.s, y, z * this.s);
  }
  raw(x: number, y: number, z: number): V3 {
    _v.set(x, y, z).applyMatrix4(this.m);
    return [_v.x, _v.y, _v.z];
  }
  rot(yaw = 0): Q4 {
    const q = this.q.clone().multiply(_q.setFromAxisAngle(Y, yaw));
    return [q.x, q.y, q.z, q.w];
  }
  sub(x: number, y: number, z: number, yaw = 0): Frame {
    const o = new Vector3(...this.p(x, y, z));
    return new Frame(o, this.q.clone().multiply(new Quaternion().setFromAxisAngle(Y, yaw)));
  }
  /** Child frame rotated about its local X (tilted pieces: awnings, broken slabs). */
  tilt(x: number, y: number, z: number, yaw: number, pitch: number, roll = 0): Frame {
    const o = new Vector3(...this.p(x, y, z));
    const q = this.q.clone().multiply(new Quaternion().setFromAxisAngle(Y, yaw))
      .multiply(new Quaternion().setFromAxisAngle(new Vector3(1, 0, 0), pitch))
      .multiply(new Quaternion().setFromAxisAngle(new Vector3(0, 0, 1), roll));
    return new Frame(o, q);
  }
  up(): V3 {
    _v.set(0, 1, 0).applyQuaternion(this.q);
    return [_v.x, _v.y, _v.z];
  }
  /** World direction of a local direction. */
  dir(x: number, y: number, z: number): V3 {
    _v.set(x, y, z).applyQuaternion(this.q);
    return [_v.x, _v.y, _v.z];
  }
  /** World point → this frame's local coordinates. */
  local(p: Vector3, out = new Vector3()): Vector3 {
    return out.copy(p).sub(this.origin).applyQuaternion(_q.copy(this.q).invert());
  }
}

export class Builder {
  data: MapData;
  constructor(seed: number, cube: { half: number; face: number }, voidMargin: number, killRadius: number) {
    this.data = {
      seed, teams: [], boxes: [], hulls: [], buildings: [], houses: [], trees: [], crates: [], spawns: {},
      statues: [], bases: [], props: [], decals: [], crystalSpots: [], ponds: [], faces: [], plates: [], nav: {}, lanes: [],
      cube, voidMargin, killRadius,
    };
  }
  box(f: Frame, x: number, y: number, z: number, hx: number, hy: number, hz: number,
    color: number, mat: MatKind, collide = true, yaw = 0) {
    this.data.boxes.push({ pos: f.p(x, y, z), quat: f.rot(yaw), half: [hx * f.s, hy, hz * f.s], color, mat, collide });
  }
  /** Box standing on local height y0. */
  block(f: Frame, x: number, y0: number, z: number, hx: number, hy: number, hz: number,
    color: number, mat: MatKind, collide = true, yaw = 0) {
    this.box(f, x, y0 + hy, z, hx, hy, hz, color, mat, collide, yaw);
  }
  /** Axis-aligned box between two local corners. */
  span(f: Frame, x0: number, y0: number, z0: number, x1: number, y1: number, z1: number, color: number, mat: MatKind, collide = true) {
    if (x1 - x0 < 1e-3 || y1 - y0 < 1e-3 || z1 - z0 < 1e-3) return;
    this.box(f, (x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2, (x1 - x0) / 2, (y1 - y0) / 2, (z1 - z0) / 2, color, mat, collide);
  }
  hull(f: Frame, pts: number[][], color: number, mat: MatKind, collide = true) {
    const points: number[] = [];
    for (const p of pts) points.push(...f.p(p[0], p[1], p[2]));
    this.data.hulls.push({ points, color, mat, collide });
  }
  /** Invisible collider (a prop model is drawn there). */
  solid(f: Frame, x: number, y0: number, z: number, hx: number, hy: number, hz: number, yaw = 0) {
    this.data.boxes.push({ pos: f.p(x, y0 + hy, z), quat: f.rot(yaw), half: [hx * f.s, hy, hz * f.s], color: 0, mat: 'paint', collide: true, hidden: true });
  }
  prop(f: Frame, model: PropModel, x: number, y0: number, z: number, scale: number, yaw = 0, team?: number) {
    this.data.props.push({ model, pos: f.p(x, y0, z), quat: f.rot(yaw), scale, team });
  }
  /** Decal lying on the floor of frame f; its text reads upright when looking along `yaw`'s forward. */
  floorDecal(f: Frame, kind: DecalDef['kind'], x: number, y0: number, z: number, w: number, h: number, yaw: number, color: number, text?: string) {
    const q = new Quaternion(...f.rot(yaw)).multiply(new Quaternion().setFromAxisAngle(new Vector3(1, 0, 0), -Math.PI / 2));
    this.data.decals.push({ kind, pos: f.p(x, y0 + 0.03, z), quat: [q.x, q.y, q.z, q.w], size: [w, h], color, text });
  }
  /** Upright decal (sign) facing the frame's local +Z after `yaw`. */
  signDecal(f: Frame, x: number, y: number, z: number, w: number, h: number, yaw: number, color: number, text: string) {
    this.data.decals.push({ kind: 'text', pos: f.p(x, y, z), quat: f.rot(yaw), size: [w, h], color, text });
  }
  tree(f: Frame, x: number, y0: number, z: number, scale: number, kind: 'tree' | 'bush') {
    this.data.trees.push({ pos: f.p(x, y0, z), up: f.up(), scale, kind });
  }
  /** A crate standing on local height y0 (half size h), or a barrel (radius r = h, height 1.2). */
  crate(f: Frame, x: number, y0: number, z: number, h: number, yaw = 0, color = 0xa0764a) {
    this.data.crates.push({ pos: f.p(x, y0 + h, z), quat: f.rot(yaw), half: [h, h, h], kind: 'crate', color });
  }
  barrel(f: Frame, x: number, y0: number, z: number, color = 0x2f6fa3) {
    this.data.crates.push({ pos: f.p(x, y0 + 0.6, z), quat: f.rot(0), half: [0.42, 0.6, 0.42], kind: 'barrel', color });
  }
}

/** Gravity plate of a face-local rectangle (in frame f): walk face at height y, normal along local `up`. */
export function plate(f: Frame, x: number, y: number, z: number, up: V3, u: V3, v: V3, hu: number, hv: number, minH: number, range: number): PlateDef {
  return { center: f.p(x, y, z), up: f.dir(...up), u: f.dir(...u), v: f.dir(...v), hu, hv, minH, range };
}

export const key = (i: number, j: number) => `${i},${j}`;
